/** A pennant: rounded top, pointed bottom. */
const pennantPath = (x: number, y: number, w: number, h: number, r: number) => {
  'worklet';
  const v = h * 0.14;
  const p = Skia.PathBuilder.Make();
  p.moveTo(x, y + r);
  p.quadTo(x, y, x + r, y);
  p.lineTo(x + w - r, y);
  p.quadTo(x + w, y, x + w, y + r);
  p.lineTo(x + w, y + h - v);
  p.lineTo(x + w / 2, y + h);
  p.lineTo(x, y + h - v);
  p.close();
  return p.build();
};

/** Saturation matrix (0 grey, 1 full colour), dimmed a little when grey. */
const satMatrix = (s: number) => {
  'worklet';
  const lr = 0.2126;
  const lg = 0.7152;
  const lb = 0.0722;
  const k = mix(0.62, 1, s);
  const a = (1 - s) * lr;
  const b = (1 - s) * lg;
  const c = (1 - s) * lb;
  return [
    (a + s) * k, b * k, c * k, 0, 0,
    a * k, (b + s) * k, c * k, 0, 0,
    a * k, b * k, (c + s) * k, 0, 0,
    0, 0, 0, 1, 0,
  ];
};

const drawPennant = (
  c: SkCanvas,
  x: number,
  y: number,
  w: number,
  h: number,
  frame: string,
  pic: SkPicture,
  picW: number,
  picH: number,
  sat: number,
  sweep: number,
  title: string[] | null,
  font: SkFont | null,
) => {
  'worklet';
  const r = w * 0.1;
  const outer = pennantPath(x, y, w, h, r);
  const fp = Skia.Paint();
  fp.setAntiAlias(true);
  fp.setColor(Skia.Color(frame));
  const lay = Skia.Paint();
  lay.setColorFilter(Skia.ColorFilter.MakeMatrix(satMatrix(sat)));
  c.saveLayer(lay);
  c.drawPath(outer, fp);
  const b = w * 0.045;
  const gap = Skia.Paint();
  gap.setAntiAlias(true);
  gap.setColor(Skia.Color('#101218'));
  c.drawPath(pennantPath(x + b, y + b, w - 2 * b, h - 2 * b, r * 0.8), gap);
  const ib = b + w * 0.03;
  const inner = pennantPath(x + ib, y + ib, w - 2 * ib, h - 2 * ib, r * 0.6);
  c.save();
  c.clipPath(inner, 1, true);
  c.translate(x + ib, y + ib);
  c.scale((w - 2 * ib) / picW, (h - 2 * ib) / picH);
  c.drawPicture(pic);
  c.restore();
  if (title && font) {
    const tp = Skia.Paint();
    tp.setAntiAlias(true);
    const st = Skia.Paint();
    st.setAntiAlias(true);
    st.setStyle(1);
    st.setStrokeWidth(4);
    st.setStrokeJoin(1);
    st.setColor(Skia.Color('#14101e'));
    tp.setColor(Skia.Color('#ffffff'));
    for (let i = 0; i < title.length; i++) {
      const ids = font.getGlyphIDs(title[i]);
      const ws = font.getGlyphWidths(ids);
      let tw = 0;
      for (let j = 0; j < ws.length; j++) tw += ws[j];
      const s = Math.min(1, (w - 2 * ib - 8) / tw);
      const ty = y + h * 0.72 + i * font.getSize() * 0.92 * s;
      c.save();
      c.translate(x + w / 2, ty);
      c.scale(s, s);
      c.drawText(title[i], -tw / 2, 0, st, font);
      c.drawText(title[i], -tw / 2, 0, tp, font);
      c.restore();
    }
  }
  c.restore();
  // the light band that sweeps across while colour floods in
  if (sweep >= 0 && sweep <= 1) {
    c.save();
    c.clipPath(outer, 1, true);
    const band = Skia.Paint();
    const bx = x - w * 0.6 + sweep * w * 2.2;
    band.setShader(
      Skia.Shader.MakeLinearGradient(
        { x: bx - w * 0.3, y },
        { x: bx + w * 0.3, y: y + h * 0.4 },
        [Skia.Color('rgba(255,255,255,0)'), Skia.Color('rgba(255,255,240,0.85)'), Skia.Color('rgba(255,255,255,0)')],
        [0, 0.5, 1],
        0,
      ),
    );
    band.setBlendMode(BlendMode.Plus);
    c.drawRect(Skia.XYWHRect(x, y, w, h), band);
    c.restore();
  }
};

type Props = { autoPlay?: boolean };

export function PixelTrophyUnlock({ autoPlay = false }: Props) {
  const reduced = useReducedMotion();
  const auto = autoPlay && !reduced;
  const insets = useSafeAreaInsets();
  const [size, setSize] = useState<{ width: number; height: number } | null>(null);
  const [active, setActive] = useState(AppState.currentState === 'active');
  useEffect(() => {
    const sub = AppState.addEventListener('change', (s) => setActive(s === 'active'));
    return () => sub.remove();
  }, []);
  const [fontsOk] = useFonts({
    'PTU-Display': require('./assets/fonts/LilitaOne-Regular.ttf'),
    'PTU-Medium': require('./assets/fonts/Inter-Medium.ttf'),
    'PTU-SemiBold': require('./assets/fonts/Inter-SemiBold.ttf'),
  });
  const titleFont = useFont(require('./assets/fonts/LilitaOne-Regular.ttf'), 23);

  const w = size?.width ?? 402;
  const h = size?.height ?? 874;
  const ROW_Y = insets.top + 186;
  const SLOT = BW + 18;
  const GAP = (w - 48 - 4 * SW) / 3;
  const GRID_Y = ROW_Y + BH + 82;
  const gridPos = (i: number) => {
    'worklet';
    return { x: 24 + (i % 4) * (SW + GAP), y: GRID_Y + Math.floor(i / 4) * (SH + 58) };
  };

  // the pictures, made once
  const art = useMemo(() => {
    const big: Record<string, SkPicture> = {};
    const small: Record<string, SkPicture> = {};
    for (const s of [...RECENT, NEW]) big[s.scene] = scenePicture(s.scene, 32, 44, PX_BIG);
    for (const g of GRID) small[g.scene] = scenePicture(g.scene, 24, 30, PX_SMALL);
    return { big, small };
  }, []);

  const play = usePtuAudio(!reduced);
  const cue = (c: Cue) => play(c);
  const buzz = (kind: number) => {
    if (process.env.EXPO_OS === 'web') return;
    if (kind === 2) Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success).catch(() => {});
    else if (kind === 3) Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning).catch(() => {});
    else Haptics.impactAsync(kind === 1 ? Haptics.ImpactFeedbackStyle.Medium : Haptics.ImpactFeedbackStyle.Light).catch(() => {});
  };

  const time = useSharedValue(0);
  const clock = useSharedValue(0);
  const last = useSharedValue(-10);
  const tick = useSharedValue(0);
  // touch timeline: when the unlock and the put-back began (clock), and which locked card shakes
  const seq = useSharedValue({ a0: -100, b0: -100, shake: -1, shakeAt: -10, landed: 0 });
  const ch = useSharedValue(channels(-1, -1));
  const debugT = useSharedValue(-1);
  const [earned, setEarned] = useState(false);

  useEffect(() => {
    if (!__DEV__) return;
    const g = globalThis as { __pixelTrophy?: unknown };
    g.__pixelTrophy = { at: (t: number) => debugT.set(t), play: () => debugT.set(-1), state: () => debugState };
    return () => {
      delete g.__pixelTrophy;
    };
  }, [debugT]);
  const mirror = (s: string) => {
    debugState = s;
  };

  const frameCb = useFrameCallback((info) => {
    const dt = Math.min((info.timeSincePreviousFrame ?? 16) / 1000, 0.05);
    const now = clock.get() + dt;
    clock.set(now);
    const dbg = debugT.get();
    const sq = seq.get();
    let t = time.get();
    let a = -1;
    let b = -1;
    if (dbg >= 0) {
      t = dbg;
      const ab = scriptAB(t);
      a = ab.a;
      b = ab.b;
    } else {
      const touched = now - last.get() < 2;
      if (auto && !touched && sq.a0 < -50) {
        t += dt;
        if (t >= LOOP) t -= LOOP;
        const ab = scriptAB(t);
        a = ab.a;
        b = ab.b;
      } else {
        a = sq.a0 > -50 ? now - sq.a0 : -1;
        b = sq.b0 > -50 ? now - sq.b0 : -1;
        if (b > 1.4) {
          // put back: the touch timeline is done, autoplay may resume from where it is
          sq.a0 = -100;
          sq.b0 = -100;
        }
      }
    }
    const c = channels(a, b);
    if (reduced) {
      c.fly = 0;
      c.sweep = -1;
      c.pulse = 0;
    }
    ch.set(c);
    if (c.earned === 1 && sq.landed === 0) {
      sq.landed = 1;
      scheduleOnRN(setEarned, true);
      if (sq.a0 > -50) {
        scheduleOnRN(cue, 'land');
        scheduleOnRN(buzz, 2);
      }
    } else if (c.earned === 0 && sq.landed === 1) {
      sq.landed = 0;
      scheduleOnRN(setEarned, false);
    }
    time.set(t);
    if (__DEV__ && Math.floor(now * 4) !== Math.floor((now - dt) * 4)) {
      scheduleOnRN(mirror, `t=${t.toFixed(2)} a=${a.toFixed(2)} b=${b.toFixed(2)} fly=${c.fly.toFixed(2)}`);
    }
    tick.set(tick.get() + 1);
  }, false);

  useEffect(() => {
    frameCb.setActive(active && size !== null);
    return () => frameCb.setActive(false);
  }, [active, size, frameCb]);

  const picture = useDerivedValue(() => {
    tick.get();
    const rec = Skia.PictureRecorder();
    const c = rec.beginRecording(Skia.XYWHRect(0, 0, w, h));
    const k = ch.get();
    const sq = seq.get();
    const now = clock.get();
    // the warm glow at the top of the sheet
    const glow = Skia.Paint();
    glow.setShader(
      Skia.Shader.MakeRadialGradient({ x: w / 2, y: insets.top - 20 }, w * 0.9, [Skia.Color('rgba(150,110,40,0.55)'), Skia.Color('rgba(60,45,20,0.2)'), Skia.Color('rgba(14,14,16,0)')], [0, 0.45, 1], 0),
    );
    c.drawRect(Skia.XYWHRect(0, 0, w, h), glow);
    // the recent row, sliding over to make room
    for (let i = 0; i < RECENT.length; i++) {
      const rcd = RECENT[i];
      const x = 24 + (i + k.shift) * SLOT;
      if (x > w + 10) continue;
      drawPennant(c, x, ROW_Y, BW, BH, rcd.frame, art.big[rcd.scene], 32 * PX_BIG, 44 * PX_BIG, 1, -1, rcd.title, titleFont);
    }
    // the grid
    for (let i = 0; i < GRID.length; i++) {
      const g = GRID[i];
      const p = gridPos(i);
      if (p.y > h) continue;
      let sat = g.earned ? 1 : 0;
      let sweep = -1;
      let scale = 1;
      let dx = 0;
      if (i === TARGET) {
        sat = k.colour;
        sweep = k.sweep;
        scale = 1 + 0.08 * k.pulse;
      }
      if (i === sq.shake) {
        const s = now - sq.shakeAt;
        if (s >= 0 && s < 0.45) dx = Math.sin(s * 40) * 5 * Math.exp(-s * 7);
      }
      const frame = g.earned || (i === TARGET && k.colour > 0.02) ? (i === TARGET ? NEW.frame : '#ffb23a') : '#5b5d66';
      c.save();
      c.translate(p.x + SW / 2 + dx, p.y + SH / 2);
      c.scale(scale, scale);
      c.translate(-SW / 2, -SH / 2);
      drawPennant(c, 0, 0, SW, SH, frame, art.small[g.scene], 24 * PX_SMALL, 30 * PX_SMALL, sat, sweep, null, null);
      // a padlock on a locked card (as an achievements carousel marks them), gone as colour floods in
      const lockA = g.earned ? 0 : i === TARGET ? 1 - Math.min(1, k.colour * 3) : 1;
      if (lockA > 0.01) {
        const lp = Skia.Paint();
        lp.setAntiAlias(true);
        lp.setColor(Skia.Color('#1a1b20'));
        lp.setAlphaf(0.85 * lockA);
        c.drawCircle(SW / 2, SH * 0.46, 15, lp);
        const body = Skia.Paint();
        body.setAntiAlias(true);
        body.setColor(Skia.Color('#d9dbe2'));
        body.setAlphaf(lockA);
        c.drawRRect(Skia.RRectXY(Skia.XYWHRect(SW / 2 - 7, SH * 0.46 - 2, 14, 11), 2.5, 2.5), body);
        const sh = Skia.Paint();
        sh.setAntiAlias(true);
        sh.setStyle(1);
        sh.setStrokeWidth(2.4);
        sh.setColor(Skia.Color('#d9dbe2'));
        sh.setAlphaf(lockA);
        // the shackle lifts open as the card unlocks
        const lift = i === TARGET ? Math.min(1, k.colour * 3) * 4 : 0;
        c.drawArc(Skia.XYWHRect(SW / 2 - 4.5, SH * 0.46 - 9 - lift, 9, 12), 180, 180, false, sh);
      }
      c.restore();
    }
    // the copy in flight: from the grid slot up on an arc into the front of the row
    if (k.fly > 0.001 && k.gone < 0.999) {
      const from = gridPos(TARGET);
      const fx = from.x + SW / 2;
      const fy = from.y + SH / 2;
      const tx = 24 + BW / 2;
      const ty = ROW_Y + BH / 2;
      const x = mix(fx, tx, k.fly);
      const y = mix(fy, ty, k.fly) - Math.sin(k.fly * Math.PI) * 90;
      const s = mix(SW / BW, 1, smooth(k.fly)) * (1 + k.bounce) * (1 - 0.25 * k.gone);
      const rot = Math.sin(k.fly * Math.PI) * -10;
      c.save();
      c.translate(x, y);
      c.rotate(rot, 0, 0);
      c.scale(s, s);
      const layer = Skia.Paint();
      layer.setAlphaf(1 - k.gone);
      c.saveLayer(layer);
      // a soft shadow while it is up in the air
      const sh = Skia.Paint();
      sh.setColor(Skia.Color('#000000'));
      sh.setAlphaf(0.45 * Math.sin(k.fly * Math.PI));
      sh.setMaskFilter(Skia.MaskFilter.MakeBlur(0, 14, true));
      c.drawRect(Skia.XYWHRect(-BW / 2 + 10, -BH / 2 + 24, BW - 20, BH - 20), sh);
      drawPennant(c, -BW / 2, -BH / 2, BW, BH, NEW.frame, art.big[NEW.scene], 32 * PX_BIG, 44 * PX_BIG, 1, -1, NEW.title, titleFont);
      c.restore();
      c.restore();
    }
    return rec.finishRecordingAsPicture();
  }, [w, h, art, titleFont, ROW_Y, GRID_Y, SLOT, GAP]);

  // ---------------------------------------------------------------- copy, count, touch
  const barStyle = useAnimatedStyle(() => {
    tick.get();
    const k = ch.get();
    const grow = k.earned ? smooth(1) : 0;
    return { width: `${mix(4 / 67, 5 / 67, grow) * 100}%` };
  });
  const count = earned ? 5 : 4;

  const tap = Gesture.Tap().onEnd((e) => {
    last.set(clock.get());
    const sq = seq.get();
    const now = clock.get();
    for (let i = 0; i < GRID.length; i++) {
      const p = gridPos(i);
      if (e.x > p.x && e.x < p.x + SW && e.y > p.y && e.y < p.y + SH) {
        if (i === TARGET) {
          const k = ch.get();
          if (k.earned === 0 && sq.a0 < -50) {
            sq.a0 = now;
            sq.b0 = -100;
            scheduleOnRN(cue, 'unlock');
            scheduleOnRN(buzz, 1);
          } else if (k.earned === 1) {
            if (sq.a0 < -50) sq.a0 = now - 3;
            sq.b0 = now;
            scheduleOnRN(buzz, 0);
          }
        } else if (!GRID[i].earned) {
          sq.shake = i;
          sq.shakeAt = now;
          scheduleOnRN(buzz, 3);
        }
        return;
      }
    }
  });
  useAnimatedReaction(
    () => {
      tick.get();
      return ch.get().fly > 0.05 && ch.get().fly < 0.95 ? 1 : 0;
    },
    (n, prev) => {
      if (n === 1 && prev === 0 && seq.get().a0 > -50) scheduleOnRN(cue, 'whoosh');
    },
  );

  const onLayout = (e: LayoutChangeEvent) => {
    const { width, height } = e.nativeEvent.layout;
    if (!size || size.width !== width || size.height !== height) setSize({ width, height });
  };
  if (!fontsOk) return <View style={styles.screen} onLayout={onLayout} />;

  return (
    <View style={styles.screen} onLayout={onLayout}>
      <StatusBar style="light" />
      <GestureDetector gesture={tap}>
        <View style={StyleSheet.absoluteFill}>
          {size ? (
            <Canvas style={StyleSheet.absoluteFill}>
              <Picture picture={picture} />
            </Canvas>
          ) : null}
        </View>
      </GestureDetector>
      <Text style={[styles.title, { top: insets.top + 26 }]} allowFontScaling={false} accessibilityRole="header">
        Achievements
      </Text>
      <View style={[styles.progress, { top: insets.top + 84 }]} pointerEvents="none">
        <View style={styles.progressRow}>
          <Text style={styles.count} allowFontScaling={false} accessibilityLiveRegion="polite">
            {count} / 67 earned
          </Text>
          <Text style={styles.count} allowFontScaling={false}>
            {Math.floor((count / 67) * 100)}%
          </Text>
        </View>
        <View style={styles.track}>
          <Animated.View style={[styles.fill, barStyle]} />
        </View>
      </View>
      <View style={[styles.recentPill, { top: ROW_Y - 44 }]} pointerEvents="none">
        <Text style={styles.recentText} allowFontScaling={false}>
          Recently earned
        </Text>
      </View>
      <View style={[styles.divider, { top: GRID_Y - 46 }]} pointerEvents="none">
        <View style={[styles.rule, styles.ruleL]} />
        <Text style={styles.dividerText} allowFontScaling={false}>
          COMMON
        </Text>
        <View style={[styles.rule, styles.ruleR]} />
      </View>
      {GRID.map((g, i) => {
        const x = 24 + (i % 4) * (SW + GAP);
        const y = GRID_Y + Math.floor(i / 4) * (SH + 58) + SH + 8;
        const lit = g.earned || (i === TARGET && earned);
        return (
          <Text
            key={g.name}
            style={[styles.name, { left: x - 10, top: y, width: SW + 20 }, !lit && styles.nameLocked]}
            allowFontScaling={false}
            accessible
            accessibilityRole="button"
            accessibilityLabel={`${g.name}, ${lit ? 'earned' : 'locked'}`}
          >
            {g.name}
          </Text>
        );
      })}
      <View style={[styles.close, { bottom: insets.bottom + 14 }]} accessible accessibilityRole="button" accessibilityLabel="Close">
        <Text style={styles.closeText} allowFontScaling={false}>
          Close
        </Text>
      </View>
    </View>
  );
}

