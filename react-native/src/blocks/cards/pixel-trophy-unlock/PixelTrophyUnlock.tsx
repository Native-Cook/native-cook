/*
 Pixel Trophy Unlock — the achievements screen of an invented step-counting app.

 Look (the pin, a still): a black sheet with a warm glow, "Achievements", 4 / 67 earned with a green
 bar, "Recently earned" over a row of big pennant-shaped trophy cards with framed pixel-art scenes
 and chunky titles, a COMMON divider and a grid of small pennants, the earned one in colour and the
 locked ones grey. The pin's cards are illustrated characters; ours are pixel scenes generated by
 rules with an emblem each (no image files).

 Motion (ours): a trophy is earned. Its grey pennant in the grid pulses, a light band sweeps across
 it and colour floods in behind the band; a copy lifts out, grows and flies up on an arc into the
 front of the Recently earned row, which slides over to make room, lands with a bounce, and the
 count rolls to 5 / 67 while the bar grows. Tap the glowing card to earn it, tap it again to put it
 back; a locked card shakes.

 autoPlay: LOOP = 8 s. 1.0 s pulse, 1.2-1.9 s colour sweep, 1.95-2.85 s flight, 2.85 s landing;
 6.6-7.4 s it is put back. Frame 8 s equals frame 0. Reduced motion: colour fades in, no flight.
*/

let debugState = '';
const LOOP = 8;
const BW = 128;
const BH = 176;
const SW = 80;
const SH = 98;
const PX_BIG = 4;
const PX_SMALL = 3;

const clamp01 = (v: number) => {
  'worklet';
  return v < 0 ? 0 : v > 1 ? 1 : v;
};
const mix = (a: number, b: number, k: number) => {
  'worklet';
  return a + (b - a) * k;
};
const smooth = (k: number) => {
  'worklet';
  const x = clamp01(k);
  return x * x * (3 - 2 * x);
};
const easeInOut = (k: number) => {
  'worklet';
  const x = clamp01(k);
  return x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2;
};
const easeOutBack = (k: number) => {
  'worklet';
  const x = clamp01(k);
  const c1 = 1.4;
  return 1 + (c1 + 1) * Math.pow(x - 1, 3) + c1 * Math.pow(x - 1, 2);
};

/** The unlock's channels a seconds after it began and b seconds after the put-back began (b < 0: not yet). */
const channels = (a: number, b: number) => {
  'worklet';
  const pulse = a >= 0 && a < 0.3 ? Math.sin((a / 0.3) * Math.PI) : 0;
  let colour = smooth((a - 0.2) / 0.7);
  let fly = easeInOut((a - 0.95) / 0.9);
  let shift = easeOutBack((a - 1.25) / 0.62);
  const landAt = a - 1.85;
  const bounce = landAt >= 0 && landAt < 0.5 ? Math.sin(landAt * 18) * Math.exp(-landAt * 9) * 0.06 : 0;
  let earned = a >= 1.85 ? 1 : 0;
  let gone = 0;
  if (b >= 0) {
    gone = smooth(b / 0.45);
    shift = shift * (1 - easeInOut((b - 0.2) / 0.6));
    colour = colour * (1 - smooth((b - 0.0) / 0.6));
    earned = b >= 0.4 ? 0 : earned;
    if (b > 0.8) fly = 0;
  }
  return { pulse, colour, fly, shift, bounce, earned, gone, sweep: a >= 0.2 && a < 1.0 ? (a - 0.2) / 0.8 : -1 };
};
const scriptAB = (t: number) => {
  'worklet';
  return { a: t >= 1.0 ? t - 1.0 : -1, b: t >= 6.6 ? t - 6.6 : -1 };
};

