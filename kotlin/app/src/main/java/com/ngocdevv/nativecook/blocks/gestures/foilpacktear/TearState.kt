    fun resetFrom(other: TearState) {
        pose = other.pose
        phase = other.phase
        age = other.age
        clock = other.clock
        reduced = other.reduced
        hold = other.hold
        down = other.down
        downAt = other.downAt
        downX = other.downX
        downY = other.downY
        fingerX = other.fingerX
        fingerY = other.fingerY
