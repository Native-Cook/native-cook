    var revealY: Double = CARD.peekY,
    var revealTiltX: Double = 0.0,
    var revealTiltY: Double = 0.0,
    var collectY: Double = CARD.revealY,
    var collectScale: Double = CARD.revealScale,
    var pressAge: Double = 0.0,
    var tiltHomeAge: Double = 1.0,
    var newPack: Boolean = false,
    var events: MutableList<Double> = mutableListOf(),
