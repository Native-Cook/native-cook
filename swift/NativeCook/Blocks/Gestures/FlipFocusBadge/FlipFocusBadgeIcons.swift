    static let gear: Path = {
        var p = Path()
        for i in 0..<8 {
            let a = Double(i) / 8 * .pi * 2
            let pairs = [(7.8, a - .pi / 8 + 0.02), (7.8, a - 0.33), (10.0, a - 0.2), (10.0, a + 0.2), (7.8, a + 0.33)]
            for (j, pair) in pairs.enumerated() {
                let x = ((12 + pair.0 * sin(pair.1)) * 100).rounded() / 100
                let y = ((12 - pair.0 * cos(pair.1)) * 100).rounded() / 100
                if i == 0 && j == 0 { p.move(to: CGPoint(x: x, y: y)) } else { p.addLine(to: CGPoint(x: x, y: y)) }
            }
        }
        p.closeSubpath()
        p.addEllipse(in: CGRect(x: 8.5, y: 8.5, width: 7, height: 7))
        return p
    }()
